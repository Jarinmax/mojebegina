CREATE TABLE "eshop_coupons" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"code" text NOT NULL,
	"discount_type" text NOT NULL,
	"amount" numeric(10, 2) NOT NULL,
	"free_shipping" boolean DEFAULT false NOT NULL,
	"expires_at" timestamp with time zone,
	"minimum_amount_kc" integer,
	"maximum_amount_kc" integer,
	"individual_use" boolean DEFAULT false NOT NULL,
	"product_slugs" text[] DEFAULT '{}'::text[] NOT NULL,
	"excluded_product_slugs" text[] DEFAULT '{}'::text[] NOT NULL,
	"category_slugs" text[] DEFAULT '{}'::text[] NOT NULL,
	"excluded_category_slugs" text[] DEFAULT '{}'::text[] NOT NULL,
	"email_restrictions" text[] DEFAULT '{}'::text[] NOT NULL,
	"usage_limit" integer,
	"usage_limit_per_user" integer,
	"limit_usage_to_x_items" integer,
	"used_before" integer DEFAULT 0 NOT NULL,
	"used_by_before" text[] DEFAULT '{}'::text[] NOT NULL,
	"is_active" boolean DEFAULT true NOT NULL,
	"note" text,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "eshop_coupons_code_unique" UNIQUE("code"),
	CONSTRAINT "eshop_coupons_code_lower" CHECK ("eshop_coupons"."code" = lower("eshop_coupons"."code") AND length("eshop_coupons"."code") BETWEEN 1 AND 64),
	CONSTRAINT "eshop_coupons_type_check" CHECK ("eshop_coupons"."discount_type" IN ('percent', 'fixed_cart', 'fixed_product')),
	CONSTRAINT "eshop_coupons_amount_check" CHECK ("eshop_coupons"."amount" >= 0 AND ("eshop_coupons"."discount_type" <> 'percent' OR "eshop_coupons"."amount" <= 100)),
	CONSTRAINT "eshop_coupons_limits_check" CHECK (("eshop_coupons"."usage_limit" IS NULL OR "eshop_coupons"."usage_limit" > 0) AND ("eshop_coupons"."usage_limit_per_user" IS NULL OR "eshop_coupons"."usage_limit_per_user" > 0) AND ("eshop_coupons"."limit_usage_to_x_items" IS NULL OR "eshop_coupons"."limit_usage_to_x_items" > 0) AND "eshop_coupons"."used_before" >= 0)
);
